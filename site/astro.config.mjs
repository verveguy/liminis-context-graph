// @ts-check
import { readdirSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'astro/config'
import starlight from '@astrojs/starlight'
import react from '@astrojs/react'
import { remarkC4 } from './src/plugins/remark-c4.mjs'
import { PAGES } from './src/pages-order.mjs'

const REPO = new URL('../', import.meta.url)
const GITHUB = 'https://github.com/verveguy/liminis-context-graph'

/**
 * The version this site documents, read from the workspace manifest.
 *
 * The Jekyll site carried its own copy in _config.yml, with a CI job asserting
 * the two matched. Reading the one that ships removes the second copy, and with
 * it the class of failure that job existed to catch.
 */
function workspaceVersion() {
  // DOCS_VERSION overrides, for the republish path in ADR-0477 (FR-006): a
  // version rebuilt from a corrected branch rather than its tag must still be
  // labelled with the version it documents. The Jekyll build did this by
  // sed-patching _config.yml before building; an environment variable does the
  // same job without editing a checked-in file.
  if (process.env.DOCS_VERSION) return process.env.DOCS_VERSION
  const cargo = readFileSync(new URL('Cargo.toml', REPO), 'utf8')
  const section = cargo.split('[workspace.package]')[1]
  const match = section && /^version\s*=\s*"([^"]+)"/m.exec(section)
  if (!match) throw new Error('no [workspace.package] version in Cargo.toml')
  return match[1]
}

/**
 * Where this build will be served from.
 *
 * Every published version keeps its own copy at /liminis-context-graph/vX.Y.Z/,
 * with the latest stable also at the root (ADR-0477). Same source, two bases,
 * so the base cannot be a constant — this is the Astro equivalent of the
 * `jekyll build --baseurl` override that scheme already relied on.
 */
function siteBase() {
  return process.env.DOCS_BASE ?? '/liminis-context-graph'
}

/**
 * The 84 architecture decision records were published by the Jekyll site and
 * are not part of this one: they are an immutable engineering log, not
 * documentation for someone running the engine, and putting them in the sidebar
 * buried the pages that are.
 *
 * They keep their URLs regardless. Every one of those addresses is live today
 * and may be linked from anywhere, so each redirects to the record on GitHub
 * rather than turning into a 404. Generated from the directory, so a new ADR is
 * covered by existing it rather than by remembering to add a line here.
 */
function adrRedirects() {
  const entries = readdirSync(new URL('docs/adr/', REPO))
    .filter((f) => f.endsWith('.md'))
    .map((f) => f.replace(/\.md$/, ''))

  return Object.fromEntries(
    entries.map((slug) => [`/adr/${slug}`, `${GITHUB}/blob/main/docs/adr/${slug}.md`]),
  )
}

// Served as a GitHub Pages project site. The account carries a Pages custom
// domain on the user site, so this resolves to
// https://v3rv.com/liminis-context-graph/ rather than verveguy.github.io — the
// subpath is the same either way.
export default defineConfig({
  // `@site` so remark-c4's injected import resolves from any page depth. See
  // the note beside IMPORT_FROM in that plugin.
  vite: {
    resolve: {
      alias: { '@site': fileURLToPath(new URL('./src', import.meta.url)) },
    },
    // The footer states which release these pages describe. It is a .astro
    // component, so it cannot call workspaceVersion() itself — the value is
    // baked in here instead, from the same single source as everything else.
    define: {
      'import.meta.env.PUBLIC_DOCS_VERSION': JSON.stringify(workspaceVersion()),
    },
  },
  // Turns ```c4 fences into live islands. The source pages stay readable as
  // plain markdown on GitHub, where the fence renders as a code block beside
  // its committed SVG. See src/plugins/remark-c4.mjs.
  markdown: { remarkPlugins: [remarkC4] },
  site: 'https://v3rv.com',
  base: siteBase(),
  redirects: adrRedirects(),
  integrations: [
    react(),
    starlight({
      customCss: ['./src/styles/playground.css'],
      title: 'liminis-context-graph',
      description:
        'A local-first context graph engine. One Rust binary that turns a stream of text into a queryable graph of entities, relationships, and episodes.',
      social: { github: GITHUB },
      // Adds the version switcher beneath the stock footer. See the component.
      components: { Footer: './src/components/Footer.astro' },
      editLink: { baseUrl: `${GITHUB}/edit/main/` },
      sidebar: [
        { label: 'Overview', link: '/' },
        // Listed rather than autogenerated: the pages sit at the top level to
        // keep the URLs the Jekyll site gave them, and there is no directory to
        // point `autogenerate` at that would not also sweep up the homepage.
        // src/pages-order.mjs is the one place this order is written down.
        ...PAGES.map(([slug, label]) => ({ label, link: `/${slug}/` })),
        {
          label: 'Decision records',
          link: `${GITHUB}/blob/main/docs/adr/index.md`,
          attrs: { target: '_blank', rel: 'noopener' },
          badge: { text: 'GitHub', variant: 'note' },
        },
      ],
    }),
  ],
})

export { workspaceVersion }
